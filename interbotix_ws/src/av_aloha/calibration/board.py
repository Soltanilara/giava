"""ChArUco board definition and detection  (shared by PHASE 5).

The board geometry is CONFIGURATION, never code.  It lives in
``charuco_board.json`` next to this file and every field can be overridden
on the command line.  Nothing here assumes a printed sheet, a monitor size,
or a particular DPI: ``square_length_m`` and ``marker_length_m`` are
physical lengths that YOU measure on the board as it is actually displayed,
and they are the only things that set the scale of every downstream metric
result.

Getting them wrong scales the whole calibration: fx/fy and the distortion
coefficients are unaffected (they are dimensionless in pixels), but every
pose, every translation and eventually every reconstruction inherits the
error linearly.  Measure the displayed square with a ruler, across as many
squares as you can, and divide.

OpenCV API note
    This targets the modern ``cv2.aruco.CharucoDetector`` /
    ``board.matchImagePoints`` / ``cv2.calibrateCamera`` path.  The legacy
    helpers ``interpolateCornersCharuco`` and ``calibrateCameraCharuco``
    were REMOVED in OpenCV 5 (the version in the gym_av312 env), so they
    are not used and no fallback to them exists.

Legacy pattern
    Boards generated by OpenCV < 4.6 start with a white square in the top
    left; newer ones start black.  A mismatch makes detection fail or --
    worse -- succeed with a half-square offset.  ``legacy_pattern`` in the
    config controls it; if you generated the board with THIS module, leave
    it false.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

import numpy as np

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

try:
    import cv2
except ImportError:
    cv2 = None

BOARD_CONFIG = HERE / "charuco_board.json"

## The predefined dictionaries this module accepts, by the name used in the
## config file.  Resolved lazily so importing without cv2 still works.
DICTIONARIES = (
    "DICT_4X4_50", "DICT_4X4_100", "DICT_4X4_250", "DICT_4X4_1000",
    "DICT_5X5_50", "DICT_5X5_100", "DICT_5X5_250", "DICT_5X5_1000",
    "DICT_6X6_50", "DICT_6X6_100", "DICT_6X6_250", "DICT_6X6_1000",
    "DICT_7X7_50", "DICT_7X7_100", "DICT_7X7_250", "DICT_7X7_1000",
    "DICT_ARUCO_ORIGINAL",
)


def require_cv2() -> None:
    if cv2 is None:
        raise ImportError(
            "opencv is not available in this environment.\n"
            "  The validated env is gym_av312:\n"
            "    conda run -n gym_av312 python calibration/<script>.py")


@dataclass
class BoardSpec:
    """A ChArUco board, in physical units.

    squares_x / squares_y  number of chessboard SQUARES across and down.
                           The detectable interior corners are one fewer in
                           each direction: (squares_x-1) * (squares_y-1).
    square_length_m        physical side of one chessboard square, MEASURED.
    marker_length_m        physical side of the ArUco marker inside a white
                           square, MEASURED.  Must be < square_length_m.
    dictionary             predefined ArUco dictionary name.
    legacy_pattern         see the module docstring.
    """
    squares_x: int = 7
    squares_y: int = 5
    square_length_m: float = 0.030
    marker_length_m: float = 0.022
    dictionary: str = "DICT_5X5_250"
    legacy_pattern: bool = False
    measured: bool = False
    note: str = ""

    # -------------------------------------------------------------- #
    @property
    def n_corners(self) -> int:
        """Interior chessboard corners -- the points calibration uses."""
        return (self.squares_x - 1) * (self.squares_y - 1)

    def validate(self) -> None:
        if self.squares_x < 2 or self.squares_y < 2:
            raise ValueError("squares_x and squares_y must both be >= 2")
        if self.marker_length_m >= self.square_length_m:
            raise ValueError(
                f"marker_length_m ({self.marker_length_m}) must be smaller "
                f"than square_length_m ({self.square_length_m})")
        if self.square_length_m <= 0:
            raise ValueError("square_length_m must be positive")
        if self.dictionary not in DICTIONARIES:
            raise ValueError(f"dictionary must be one of {DICTIONARIES}")
        need = (self.squares_x * self.squares_y) // 2
        avail = int(self.dictionary.rsplit("_", 1)[-1]) \
            if self.dictionary != "DICT_ARUCO_ORIGINAL" else 1024
        if need > avail:
            raise ValueError(
                f"board needs {need} markers but {self.dictionary} only has "
                f"{avail}")

    # -------------------------------------------------------------- #
    def cv_dictionary(self):
        require_cv2()
        return cv2.aruco.getPredefinedDictionary(
            getattr(cv2.aruco, self.dictionary))

    def cv_board(self):
        require_cv2()
        self.validate()
        board = cv2.aruco.CharucoBoard(
            (self.squares_x, self.squares_y),
            float(self.square_length_m),
            float(self.marker_length_m),
            self.cv_dictionary())
        board.setLegacyPattern(bool(self.legacy_pattern))
        return board

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["interior_corners"] = self.n_corners
        d["board_size_m"] = [self.squares_x * self.square_length_m,
                             self.squares_y * self.square_length_m]
        return d

    def describe(self) -> str:
        w, h = (self.squares_x * self.square_length_m,
                self.squares_y * self.square_length_m)
        return (
            f"{self.squares_x}x{self.squares_y} squares, "
            f"square {self.square_length_m * 1e3:.3f} mm, "
            f"marker {self.marker_length_m * 1e3:.3f} mm, "
            f"{self.dictionary}, legacy={self.legacy_pattern}\n"
            f"      {self.n_corners} interior corners; "
            f"full board {w * 1e3:.1f} x {h * 1e3:.1f} mm"
            + ("" if self.measured else
               "\n      *** square/marker lengths are NOT marked as measured "
               "-- every metric\n      result downstream is scaled by them "
               "(see charuco_board.json) ***"))


