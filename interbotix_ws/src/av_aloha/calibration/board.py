def load_spec(path: Path = BOARD_CONFIG, **overrides) -> BoardSpec:
    """Read charuco_board.json, then apply any non-None CLI overrides."""
    from common import load_json

    data: Dict[str, Any] = {}
    p = Path(path)
    if p.exists():
        raw = load_json(p)
        data = {k: v for k, v in raw.items() if not k.startswith("_")}
    fields = set(BoardSpec.__dataclass_fields__)
    kwargs = {k: v for k, v in data.items() if k in fields}
    kwargs.update({k: v for k, v in overrides.items()
                   if k in fields and v is not None})
    spec = BoardSpec(**kwargs)
    spec.validate()
    return spec


def add_board_args(ap) -> None:
    """Attach the board overrides to an argparse parser."""
    g = ap.add_argument_group("board geometry (overrides charuco_board.json)")
    g.add_argument("--board-config", default=str(BOARD_CONFIG))
    g.add_argument("--squares-x", type=int, default=None)
    g.add_argument("--squares-y", type=int, default=None)
    g.add_argument("--square-length", type=float, default=None,
                   dest="square_length_m",
                   help="physical square side in METRES (measure it)")
    g.add_argument("--marker-length", type=float, default=None,
                   dest="marker_length_m",
                   help="physical marker side in METRES (measure it)")
    g.add_argument("--dictionary", default=None, choices=DICTIONARIES)
    g.add_argument("--legacy-pattern", dest="legacy_pattern",
                   action="store_true", default=None)


def spec_from_args(args) -> BoardSpec:
    return load_spec(
        Path(args.board_config),
        squares_x=getattr(args, "squares_x", None),
        squares_y=getattr(args, "squares_y", None),
        square_length_m=getattr(args, "square_length_m", None),
        marker_length_m=getattr(args, "marker_length_m", None),
        dictionary=getattr(args, "dictionary", None),
        legacy_pattern=getattr(args, "legacy_pattern", None),
    )


