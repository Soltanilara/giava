@dataclass
class Detection:
    ok: bool
    n_corners: int
    charuco_corners: Optional[np.ndarray] = None   # (N, 2) float32
    charuco_ids: Optional[np.ndarray] = None       # (N,)   int
    obj_points: Optional[np.ndarray] = None        # (N, 3) float32, board frame
    img_points: Optional[np.ndarray] = None        # (N, 2) float32, pixels
    n_markers: int = 0
    reason: str = ""


def make_detector(spec: BoardSpec):
    require_cv2()
    board = spec.cv_board()
    detector = cv2.aruco.CharucoDetector(board)
    ## Corner refinement lifts corner localisation from integer-ish to
    ## sub-pixel, which is where calibration accuracy actually comes from.
    params = detector.getDetectorParameters()
    params.cornerRefinementMethod = cv2.aruco.CORNER_REFINE_SUBPIX
    detector.setDetectorParameters(params)
    return detector, board


def detect(image: np.ndarray, detector, board,
           min_corners: int = 6) -> Detection:
    """Find the board in one image and build calibration correspondences.

    `image` may be grayscale, BGR or RGB; detection runs on gray."""
    require_cv2()
    gray = _to_gray(image)
    charuco_corners, charuco_ids, marker_corners, marker_ids = \
        detector.detectBoard(gray)

    n_markers = 0 if marker_ids is None else int(len(marker_ids))
    if charuco_ids is None or len(charuco_ids) < min_corners:
        n = 0 if charuco_ids is None else int(len(charuco_ids))
        return Detection(False, n, n_markers=n_markers,
                         reason=f"only {n} charuco corners "
                                f"(need >= {min_corners})")

    obj_points, img_points = board.matchImagePoints(charuco_corners,
                                                    charuco_ids)
    if obj_points is None or len(obj_points) < min_corners:
        return Detection(False, int(len(charuco_ids)), n_markers=n_markers,
                         reason="matchImagePoints returned too few points")

    ## A view whose corners are collinear carries no information about the
    ## board plane and makes calibrateCamera singular.
    try:
        if board.checkCharucoCornersCollinear(charuco_ids):
            return Detection(False, int(len(charuco_ids)),
                             n_markers=n_markers,
                             reason="detected corners are collinear")
    except Exception:
        pass

    return Detection(
        True, int(len(charuco_ids)),
        charuco_corners=np.asarray(charuco_corners, dtype=np.float32).reshape(-1, 2),
        charuco_ids=np.asarray(charuco_ids).reshape(-1),
        obj_points=np.asarray(obj_points, dtype=np.float32).reshape(-1, 3),
        img_points=np.asarray(img_points, dtype=np.float32).reshape(-1, 2),
        n_markers=n_markers)


def _to_gray(image: np.ndarray) -> np.ndarray:
    if image.ndim == 2:
        return image
    if image.shape[2] == 3:
        return cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    return cv2.cvtColor(image, cv2.COLOR_BGRA2GRAY)


def annotate(image: np.ndarray, det: Detection) -> np.ndarray:
    """Draw the detected corners for visual checking."""
    require_cv2()
    out = image.copy()
    if out.ndim == 2:
        out = cv2.cvtColor(out, cv2.COLOR_GRAY2BGR)
    if det.ok and det.charuco_corners is not None:
        cv2.aruco.drawDetectedCornersCharuco(
            out, det.charuco_corners.reshape(-1, 1, 2),
            det.charuco_ids.reshape(-1, 1).astype(np.int32), (0, 255, 0))
    txt = (f"{det.n_corners} corners / {det.n_markers} markers"
           if det.ok else f"REJECTED: {det.reason}")
    cv2.putText(out, txt, (8, 22), cv2.FONT_HERSHEY_SIMPLEX, 0.6,
                (0, 255, 0) if det.ok else (0, 0, 255), 2)
    return out


def generate_image(spec: BoardSpec, pixels_per_metre: float = 4000.0,
                   margin_px: int = 20,
                   size_px: Optional[Tuple[int, int]] = None) -> np.ndarray:
    """Render the board for printing or for display on a monitor.

    `pixels_per_metre` only sets the rendering resolution -- it does NOT
    determine the physical size, which depends on how the image is printed
    or displayed.  Measure the result and put the measurement in
    charuco_board.json.

    `size_px` overrides the computed output size.  It exists because
    OpenCV fits the board inside `size_px` MINUS the margins while keeping
    the squares square, so a size derived from pixels_per_metre alone
    comes out a few percent smaller per square than asked -- fine for
    printing, wrong for "render exactly N pixels per square"."""
    require_cv2()
    board = spec.cv_board()
    if size_px is None:
        w = int(round(spec.squares_x * spec.square_length_m * pixels_per_metre))
        h = int(round(spec.squares_y * spec.square_length_m * pixels_per_metre))
    else:
        w, h = (int(size_px[0]), int(size_px[1]))
    return board.generateImage((w, h), marginSize=margin_px)
